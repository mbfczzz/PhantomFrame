import assert from 'node:assert/strict';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { launchBrowser } from './browser.mjs';

const base = process.env.PREVIEW_URL || 'http://127.0.0.1:5173';
const output = 'test-results/channel-search';
await mkdir(output, { recursive: true });
const browser = await launchBrowser(), checks = [], errors = [];
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  assert.ok((await context.request.post(base + '/api/auth/login', { data: JSON.parse(await readFile('.local-credentials.json', 'utf8')) })).ok());
  const get = async path => { const r = await context.request.get(base + '/api' + path); assert.ok(r.ok()); return r.json(); };
  const providers = await get('/admin/providers'), before = await get('/admin/models');
  const provider = providers.find(p => p.protocol === 'suda');
  assert.ok(provider?.supportedCount > 20);
  const catalogPath = `/admin/providers/${provider.id}/models`;
  const expected = await get(catalogPath + '?search=image&limit=20');
  const page = await context.newPage();
  page.setDefaultTimeout(10000);
  page.on('pageerror', error => errors.push(error.message));
  let delay = 500, fail = false;
  const requests = [];
  await page.route('**/api/admin/**', async route => {
    if (route.request().method() !== 'GET') { errors.push('Unexpected admin write'); return route.abort(); }
    if (new URL(route.request().url()).pathname !== '/api' + catalogPath) return route.continue();
    const url = new URL(route.request().url());
    requests.push({ search: url.searchParams.get('search'), page: url.searchParams.get('page') });
    if (fail) return route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ message: 'temporary search error' }) });
    const response = await route.fetch();
    await new Promise(resolve => setTimeout(resolve, delay));
    await route.fulfill({ response }).catch(() => {});
  });
  const dialog = page.getByRole('dialog', { name: '渠道模型', exact: true });
  const search = dialog.getByPlaceholder('搜索上游模型 ID 或名称', { exact: true });
  const ready = () => dialog.locator('.channel-model-results[aria-busy="false"]').waitFor();
  const startMonitor = () => page.evaluate(() => {
    const samples = [];
    const run = () => {
      const modal = document.querySelector('.channel-model-dialog');
      const input = modal.querySelector('.searchbox input');
      const rect = modal.getBoundingClientRect(), field = input.getBoundingClientRect();
      samples.push({ y: rect.y, height: rect.height, inputY: field.y, loading: !!modal.querySelector('.loading'), table: !!modal.querySelector('table'), focused: document.activeElement === input });
      window.searchFrame = requestAnimationFrame(run);
    };
    window.searchSamples = samples;
    run();
  });
  const stopMonitor = () => page.evaluate(() => { cancelAnimationFrame(window.searchFrame); return window.searchSamples; });
  for (const [width, height] of [[1440, 1000], [390, 844], [320, 568]]) {
    await page.setViewportSize({ width, height });
    await page.goto(base + '/admin/providers', { waitUntil: 'networkidle' });
    await page.getByRole('button', { name: '管理模型 ' + provider.name, exact: true }).click();
    await ready();
    await search.focus();
    const initial = await dialog.boundingBox();
    const count = requests.length;
    await startMonitor();
    await search.pressSequentially('image', { delay: 45 });
    await ready();
    const samples = await stopMonitor();
    assert.ok(samples.length > 5);
    assert.ok(samples.every(item => !item.loading && item.table && item.focused));
    assert.ok(Math.max(...samples.map(s => s.y)) - Math.min(...samples.map(s => s.y)) < 1);
    assert.ok(Math.max(...samples.map(s => s.inputY)) - Math.min(...samples.map(s => s.inputY)) < 1);
    assert.ok(samples.every(s => Math.abs(s.height - initial.height) < 1));
    assert.equal(requests.length - count, 1, 'rapid typing should produce one query');
    assert.equal(await dialog.locator('tbody tr').count(), expected.items.length);
    assert.equal(await search.inputValue(), 'image');
    assert.equal(await dialog.evaluate(node => node.scrollWidth > node.clientWidth), false);
    await page.screenshot({ path: `${output}/search-${width}.png`, animations: 'disabled' });
    const emptyBounds = await dialog.boundingBox();
    await search.fill('no-model-matches-this-search');
    await ready();
    await dialog.getByRole('heading', { name: '没有匹配的渠道模型', exact: true }).waitFor();
    assert.ok(Math.abs((await dialog.boundingBox()).y - emptyBounds.y) < 1);
    await dialog.getByRole('button', { name: '清空搜索', exact: true }).click();
    await ready();
    assert.equal(await dialog.locator('tbody tr').count(), 20);
    await dialog.getByRole('button', { name: '下一页', exact: true }).click();
    await ready();
    assert.equal(await dialog.locator('.pagination > span').last().innerText(), '2 / 5');
    await search.fill('image');
    await ready();
    assert.equal(await dialog.locator('tbody tr').count(), expected.items.length);
    assert.equal(await dialog.locator('.pagination').count(), 0, 'search returns the first page even when the result is cached');
    checks.push({ width, height, requestsPerWord: 1, loaderFlashes: 0, dialogMovement: 0, inputFocusPreserved: true });
    await page.keyboard.press('Escape');
    await dialog.waitFor({ state: 'hidden' });
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: '管理模型 ' + provider.name, exact: true }).click();
  await ready();
  const composingCount = requests.length;
  await search.dispatchEvent('compositionstart');
  await search.fill('图片');
  await page.waitForTimeout(400);
  assert.equal(requests.length, composingCount);
  await search.dispatchEvent('compositionend');
  await ready();
  assert.equal(requests.at(-1).search, '图片');
  checks.push({ composition: 'no intermediate requests' });
  delay = 900;
  const slow = page.waitForRequest(request => request.url().includes('/api' + catalogPath) && new URL(request.url()).searchParams.get('search') === 'seed');
  await search.fill('seed');
  await slow;
  await search.fill('image');
  await ready();
  await page.waitForTimeout(1000);
  assert.equal(await search.inputValue(), 'image');
  assert.equal(await dialog.locator('tbody tr').count(), expected.items.length);
  checks.push({ supersededRequest: 'cannot overwrite the latest results' });
  delay = 500;
  fail = true;
  await search.fill('transient-error');
  await dialog.getByRole('heading', { name: '加载失败', exact: true }).waitFor();
  fail = false;
  await dialog.getByRole('button', { name: '重新加载', exact: true }).click();
  await ready();
  await search.fill('image');
  await ready();
  assert.equal(await dialog.locator('tbody tr').count(), expected.items.length);
  checks.push({ retry: 'recovers without closing the dialog' });
  assert.deepEqual(await get('/admin/models'), before);
  assert.deepEqual(errors, []);
  await writeFile(output + '/report.json', JSON.stringify({ checks, errors }, null, 2));
  console.log(JSON.stringify({ checks, errors }));
} finally { await browser.close(); }
